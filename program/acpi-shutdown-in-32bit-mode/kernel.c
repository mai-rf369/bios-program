//####################################################################################################
// BIOS-PROGRAM - ACPI-Shutdown-in-32bit-Mode (Kernel)
//####################################################################################################
#include "hardware.h"
#include "font8x8.h"
#include "timer.h"
#include "graphic.h"
#include "keycode.h"
#include "acpi.h"

//====================================================================================================
// Function
//====================================================================================================
//****************************************************************************************************
// Keyboard Driver
//****************************************************************************************************
//----------------------------------------------------------------------------------------------------
// Sub Routine (process_keyboard)
//----------------------------------------------------------------------------------------------------
void process_keyboard(int *key_state)
{
	while (inb(0x64) & 0x01)
	{
		unsigned char scan	=	inb(0x60);
		if (scan == 0xE0)
		{
			continue;
		}
		
		if (scan & 0x80)
		{
			key_state[scan & 0x7F]	=	0;	// Release
		}
		else
		{
			key_state[scan]		=	1;	// Press
		}
	}
}

//****************************************************************************************************
// Main
//****************************************************************************************************
//----------------------------------------------------------------------------------------------------
// Main Routine (main)
//----------------------------------------------------------------------------------------------------
void main(void)
{
	unsigned char *vram	=	(unsigned char *)VRAM;
	
	// Clear Display
	for (int i = 0; i < SCREEN_WIDTH * SCREEN_HEIGHT; i++)
	{
		vram[i]	=	0;
	}
	
	// Create Key State
	int key_state[128];
	for (int i = 0; i < 128; i++)
	{
		key_state[i]	=	0;
	}
	
	// Game Loop
	while (1)
	{
		process_keyboard(key_state);
		
		if (key_state[KEY_ESC])
		{
			system_shutdown();
		}
		
		draw_string(4, 4, "ESC: Shutdown", 15, &font8x8, vram);
		
		delay_ms(16);
	}
}
