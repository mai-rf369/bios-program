[ORG 0x7C00]
[BITS 16]

_MBR:
	CLI
	XOR	AX, AX
	MOV	DS, AX
	MOV	ES, AX
	MOV	SS, AX
	MOV	SP, 0x7C00
	
	MOV	[BOOT_DRIVE], DL
	STI
	
	MOV	AX, 0x0003
	INT	0x10
	
	MOV	AH, 0x42
	MOV	DL, [BOOT_DRIVE]
	MOV	SI, DAP
	INT	0x13
	JC	DISK_ERROR
	
	IN	AL, 0x92
	OR	AL, 2
	OUT	0x92, AL
	
	CLI
	LGDT	[GDT_DESCRIPTOR]
	
	MOV	EAX, CR0
	OR	EAX, 0x1
	MOV	CR0, EAX
	
	JMP	CODE_SEG:INIT_PM

DISK_ERROR:
	HLT
	JMP	DISK_ERROR

[BITS 32]
INIT_PM:
	MOV	AX, DATA_SEG
	MOV	DS, AX
	MOV	SS, AX
	MOV	ES, AX
	MOV	FS, AX
	MOV	GS, AX
	
	MOV	EBP, 0x90000
	MOV	ESP, EBP
	
	MOV	EAX, 0x10000
	CALL	EAX
	
	JMP	$

BOOT_DRIVE	DB	0

DAP:
	DB	0x10
	DB	0
	DW	16
	DW	0x0000
	DW	0x1000
	DQ	1

GDT_START:
	DD	0x0, 0x0
GDT_CODE:
	DW	0xFFFF, 0x0
	DB	0x0, 10011010B, 11001111B, 0x0
GDT_DATA:
	DW	0xFFFF, 0x0
	DB	0x0, 10010010B, 11001111B, 0x0
GDT_END:

GDT_DESCRIPTOR:
	DW	GDT_END - GDT_START - 1
	DD	GDT_START

CODE_SEG	EQU	GDT_CODE - GDT_START
DATA_SEG	EQU	GDT_DATA - GDT_START

	TIMES	0x01B8 - ($ - $$)	DB	0x00
	DD	0x00000000
	DW	0x0000
	DB	0x80, 0x20, 0x21, 0x00, 0x0E, 0x15, 0x50, 0x05
	DD	0x00000800, 0x003FF800
	TIMES	48	DB	0x00
	DB	0x55, 0xAA

