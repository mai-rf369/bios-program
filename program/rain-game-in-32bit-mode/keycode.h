#ifndef KEYCODE_H
#define KEYCODE_H
//****************************************************************************************************
// PS/2 Keyboard Scan Code (Set 1 Make Code)
//****************************************************************************************************
//----------------------------------------------------------------------------------------------------
// Control / Special Key
//----------------------------------------------------------------------------------------------------
#define KEY_ESC		0x01
#define KEY_BACKSPACE	0x0E
#define KEY_TAB		0x0F
#define KEY_ENTER	0x1C
#define KEY_LCTRL	0x1D
#define KEY_LSHIFT	0x2A
#define KEY_RSHIFT	0x36
#define KEY_LALT	0x38
#define KEY_SPACE	0x39
#define KEY_CAPSLOCK	0x3A
//----------------------------------------------------------------------------------------------------
// Arrow Key
//----------------------------------------------------------------------------------------------------
#define KEY_UP		0x48
#define KEY_LEFT	0x4B
#define KEY_RIGHT	0x4D
#define KEY_DOWN	0x50
//----------------------------------------------------------------------------------------------------
// Function Key
//----------------------------------------------------------------------------------------------------
#define KEY_F1		0x3B
#define KEY_F2		0x3C
#define KEY_F3		0x3D
#define KEY_F4		0x3E
//----------------------------------------------------------------------------------------------------
// Number Key
//----------------------------------------------------------------------------------------------------
#define KEY_1		0x02
#define KEY_2		0x03
#define KEY_3		0x04
//----------------------------------------------------------------------------------------------------
// Alphabet Key
//----------------------------------------------------------------------------------------------------
#define KEY_Q		0x10
#define KEY_W		0x11
#define KEY_E		0x12
#define KEY_R		0x13
#define KEY_T		0x14
#define KEY_Y		0x15
#define KEY_U		0x16
#define KEY_I		0x17
#endif
